/** Гексаграмма дня по методу "Мэй Хуа" (Слива) — расчёт по календарной дате */
export function calculateDailyHexagram(date) {
  const y = date.getFullYear(), m = date.getMonth()+1, d = date.getDate(), h = date.getHours()+1; // час считается с 1
  const upperIdx = ((y + m + d - 1) % 8) + 1;
  const lowerIdx = ((y + m + d + h - 1) % 8) + 1;
  const changingLine = ((y + m + d + h - 1) % 6) + 1; // 1-6, снизу вверх

  const num = KING_WEN_TABLE[lowerIdx-1][upperIdx-1];
  const hex = { number: num, ...HEXAGRAM_DATA[num], upper: TRIGRAMS[upperIdx], lower: TRIGRAMS[lowerIdx], changingLine };

  // Гексаграмма-результат: меняем линию changingLine (считая снизу, 1..6) на противоположную
  const bits = [...TRIGRAMS[lowerIdx].bits, ...TRIGRAMS[upperIdx].bits]; // индексы 0..5 снизу вверх
  bits[changingLine-1] = bits[changingLine-1] ? 0 : 1;
  const newLowerBits = bits.slice(0,3), newUpperBits = bits.slice(3,6);
  const findTrigramIdx = (bits3) => TRIGRAMS.findIndex(t => t && t.bits[0]===bits3[0] && t.bits[1]===bits3[1] && t.bits[2]===bits3[2]);
  const newLowerIdx = findTrigramIdx(newLowerBits), newUpperIdx = findTrigramIdx(newUpperBits);
  const resultNum = KING_WEN_TABLE[newLowerIdx-1][newUpperIdx-1];
  hex.result = { number: resultNum, ...HEXAGRAM_DATA[resultNum] };

  return hex;
}
