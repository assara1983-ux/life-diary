function reduceDigits(n) {
  while (n > 9) n = String(n).split('').reduce((a,d)=>a+Number(d),0);
  return n;
}

/** Личное число Гуа (фэн-шуй, 1-9, кроме 5) по году рождения и полу */
export function calculateKuaNumber(birthYear, gender) {
  const lastTwo = birthYear % 100;
  const reduced = reduceDigits(Math.floor(lastTwo/10) + (lastTwo%10));
  const isWoman = /жен/i.test(gender || '');
  let kua;
  if (birthYear >= 2000) {
    kua = isWoman ? reduceDigits(reduced + 6) : (9 - reduced || 9);
  } else {
    kua = isWoman ? reduceDigits(reduced + 5) : (10 - reduced === 10 ? 1 : 10 - reduced);
  }
  if (kua === 5) kua = isWoman ? 8 : 2;
  return kua;
}

